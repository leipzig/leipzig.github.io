"""Render the YAML files in data/ into Markdown pages under docs/.

Run before `zensical build` (CI does this). Pages written here are
regenerated on every run, so edit data/*.yml, not the generated .md files.
"""

import hashlib
import html
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
DOCS = ROOT / "docs"
THUMBS = DOCS / "assets" / "thumbs"

NAME_RE = re.compile(
    r"(Leipzig,\s*J(?:eremy|\.\s*N\.|\.N\.|N|\.)?|Leipzig\s+JN?\.?|"
    r"Jeremy\s+Leipzig|J\.\s*(?:N\.\s*)?Leipzig)"
)

GENERATED = "<!-- Generated by scripts/build_site.py from data/*.yml. Do not edit. -->\n"

# Fallback cover colors, picked by keywords in the title/venue.
THEMES = [
    (("hiv", "integration", "retrovir", "htlv", "viral", "mobile dna"), ("#7f1d1d", "#e11d48"), "Retroviral integration"),
    (("mitochondri", "mitomap", "haplogroup", "mtdna"), ("#78350f", "#f59e0b"), "Mitochondrial genetics"),
    (("metadata", "reproducib", "pipeline", "workflow", "peer review", "mashup"), ("#134e4a", "#14b8a6"), "Reproducible research"),
    (("species", "fish", "biodiversity", "physarum"), ("#14532d", "#84cc16"), "Biodiversity informatics"),
    (("clozapine", "ketamine", "neuro", "alzheimer", "brain"), ("#3b0764", "#a855f7"), "Neuroscience"),
    (("heart", "autism", "congenital", "disease", "adverse"), ("#1e3a8a", "#3b82f6"), "Human genetics"),
    (("splic", "gene", "genom", "rna", "irf"), ("#064e3b", "#22c55e"), "Genomics"),
]
DEFAULT_THEME = (("#0f172a", "#64748b"), "Bioinformatics")


def load(name):
    return yaml.safe_load((DATA / f"{name}.yml").read_text())


def esc(s):
    return html.escape(str(s or ""), quote=True)


def bold_me(text):
    text = re.sub(r"</?(?:b|strong)>", "", text or "")
    return NAME_RE.sub(r"<b>\1</b>", text)


def authors_of(citation):
    """The author list of a citation: everything before the '(YYYY)'."""
    m = re.search(r"^(.*?)[\s.,]*\(\d{4}[a-z]?\)", citation or "")
    return bold_me(m.group(1).strip() if m else citation)


def theme_for(text):
    t = text.lower()
    for keys, colors, topic in THEMES:
        if any(k in t for k in keys):
            return colors, topic
    return DEFAULT_THEME


def cover_svg(seed, label, sub, theme):
    """A generated cover: gradient, a seeded field of nodes and arcs, and a label."""
    h = hashlib.sha256(seed.encode()).digest()
    (dark, light), topic = theme
    if label is None:  # publications: the card already shows year and venue
        label, sub = topic, "Publication"
    size = min(80, int(1150 / max(len(label), 1)))
    shapes = []
    for i in range(14):
        x = h[i] / 255 * 800
        y = h[i + 14] / 255 * 500
        r = 3 + h[(i + 7) % 32] % 9
        shapes.append(f'<circle cx="{x:.0f}" cy="{y:.0f}" r="{r}" fill="#fff" fill-opacity=".18"/>')
        if i:
            px, py = h[i - 1] / 255 * 800, h[i + 13] / 255 * 500
            shapes.append(
                f'<path d="M{px:.0f} {py:.0f} Q400 {250 + (h[i] - 128):.0f} {x:.0f} {y:.0f}" '
                f'stroke="#fff" stroke-opacity=".12" fill="none" stroke-width="1.5"/>'
            )
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 500" width="800" height="500">
<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
<stop offset="0" stop-color="{dark}"/><stop offset="1" stop-color="{light}"/></linearGradient></defs>
<rect width="800" height="500" fill="url(#g)"/>
{''.join(shapes)}
<text x="48" y="420" font-family="Fraunces, Georgia, serif" font-size="{size}" font-weight="600" fill="#fff">{esc(label)}</text>
<text x="52" y="458" font-family="Inter, Helvetica, sans-serif" font-size="22" letter-spacing="3" fill="#fff" fill-opacity=".8">{esc(sub.upper())}</text>
</svg>
"""


def thumb(kind, item_id, label, sub, text):
    for ext in ("jpg", "png", "webp"):
        if (THUMBS / kind / f"{item_id}.{ext}").exists():
            return f"assets/thumbs/{kind}/{item_id}.{ext}", False
    out = THUMBS / "generated" / f"{kind}-{item_id}.svg"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(cover_svg(item_id, label, sub, theme_for(text)))
    return f"assets/thumbs/generated/{kind}-{item_id}.svg", True


def pub_card(p, prefix=""):
    src, generated = thumb("pubs", p["id"], None, "", p["title"] + " " + (p.get("venue") or ""))
    link = p.get("url")
    kind = "Book" if "Mashups" in p["title"] else "Dissertation" if "Robustness" in p["title"] else "Paper"
    search = esc(f'{p["title"]} {p.get("venue")} {p["year"]} {p.get("citation")}'.lower())
    return f"""<article class="pub-card" data-search="{search}">
  <a class="pub-card__media{' is-generated' if generated else ''}" href="{esc(link)}" tabindex="-1" aria-hidden="true">
    <img src="{prefix}{src}" alt="" loading="lazy">
  </a>
  <div class="pub-card__body">
    <p class="eyebrow"><span>{esc(p.get('venue'))}</span><span>{p['year']}</span></p>
    <h3><a href="{esc(link)}">{esc(p['title'])}</a></h3>
    <p class="pub-card__authors">{authors_of(p.get('citation'))}</p>
    <p class="pub-card__summary">{esc(p.get('summary'))}</p>
    <a class="pub-card__link" href="{esc(link)}">{kind} &rarr;</a>
  </div>
</article>"""


def sw_card(s, prefix=""):
    src, generated = thumb("software", s["id"], s["name"], s.get("language") or "", s["name"] + " " + (s.get("summary") or ""))
    link = prefix + s["page"] if s.get("page") else s.get("url")
    tag = "a" if link else "div"
    href = f' href="{esc(link)}"' if link else ""
    meta = " · ".join(str(x) for x in (s.get("language"), s.get("year")) if x)
    return f"""<{tag} class="sw-card"{href}>
  <div class="sw-card__media{' is-generated' if generated else ''}"><img src="{prefix}{src}" alt="" loading="lazy"></div>
  <div class="sw-card__body">
    <p class="eyebrow"><span>{esc(meta)}</span></p>
    <h3>{esc(s['name'])}{' <span class="badge">Case study</span>' if s.get('page') else ''}</h3>
    <p>{esc(s.get('summary'))}</p>
  </div>
</{tag}>"""


def write(name, text):
    (DOCS / name).write_text(text)


