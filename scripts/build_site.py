def build_talks(talks, teaching):
    t = "\n".join(
        f'<li class="tl-item"><p class="tl-when">{x["year"]}</p><div class="tl-body"><h3>{esc(x["title"])}</h3>'
        f'<p class="tl-org">{esc(x.get("type"))} · {esc(x.get("location"))}</p><p>{esc(x.get("summary"))}</p></div></li>'
        for x in talks
    )
    teach = "\n\n".join(
        f'### {x["title"]}\n\n<p class="tl-org">{esc(x.get("role"))} · {esc(x.get("venue"))} · {esc(x.get("location"))}</p>\n\n'
        + re.sub(r"^## ", "#### ", x.get("summary") or "", flags=re.M)
        for x in teaching
    )
    write("talks.md", f"""---
title: Talks & Teaching
description: Conference presentations and courses.
---
{GENERATED}
# Talks & Teaching

## Talks

<ol class="timeline">
{t}
</ol>

## Teaching

{teach}
""")


def main():
    profile = load("profile")
    pubs = load("publications")
    software = load("software")
    (THUMBS / "generated").mkdir(parents=True, exist_ok=True)
    for f in (THUMBS / "generated").glob("*.svg"):
        f.unlink()
    build_home(profile, pubs, software)
    build_publications(pubs)
    build_software(software)
    build_experience(profile)
    build_talks(load("talks"), load("teaching"))


if __name__ == "__main__":
    main()
