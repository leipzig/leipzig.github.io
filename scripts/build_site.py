def build_publications(pubs):
    by_year = {}
    for p in pubs:
        by_year.setdefault(p["year"], []).append(p)
    blocks = []
    for year in sorted(by_year, reverse=True):
        cards = "\n".join(pub_card(p, "../") for p in by_year[year])
        blocks.append(f'<section class="year-group" data-year="{year}">\n<h2 class="year">{year}</h2>\n<div class="pub-list">\n{cards}\n</div>\n</section>')
    write("publications.md", f"""---
title: Publications
description: Peer-reviewed papers, chapters, a book and a dissertation.
hide: [navigation, toc]
---
{GENERATED}
# Publications

<p class="lede">Forty-plus papers across HIV integration, mitochondrial genetics, congenital heart disease and reproducible computational research, with an <b>h-index of 30</b>. My name is in bold in each author list.</p>

<div class="toolbar">
<input id="pub-filter" type="search" placeholder="Filter by title, journal, author or year" aria-label="Filter publications">
<a class="md-button" href="https://scholar.google.com/citations?user=dTC-vJIAAAAJ&hl=en">Google Scholar</a>
<a class="md-button" href="https://orcid.org/0000-0001-7224-9620">ORCID</a>
</div>
<p id="pub-count" class="muted"></p>

{chr(10).join(blocks)}
""")


